from __future__ import annotations

import VeraGridEngine.api as gce

from trunk.ai.ai_operator.config import OperatorEnvConfig
from trunk.ai.ai_operator.environment import VeraGridOperatorEnv
from trunk.ai.ai_operator.trainer import RolloutRecord
from trunk.ai.ai_operator.trainer import run_random_rollout


def run_demo(grid_path: str, steps: int = 10, seed: int = 7) -> list[RolloutRecord]:
    """
    Run a baseline random operator rollout over a VeraGrid grid file.

    :param grid_path:
        Path to a VeraGrid-readable grid file.
    :param steps:
        Maximum number of rollout steps.
    :param seed:
        Random seed for the baseline sampler.
    :return:
        Rollout records generated by the demo run.
    """

    # The demo path stays explicit and importable so other modules can call it
    # directly without relying on command line parsing.
    grid: object = gce.open_file(grid_path)
    env: VeraGridOperatorEnv = VeraGridOperatorEnv(
        grid=grid,
        config=OperatorEnvConfig(max_steps=steps),
    )
    history: list[RolloutRecord] = run_random_rollout(env=env, steps=steps, seed=seed)

    print(f"Executed {len(history)} operator steps")
    record: RolloutRecord
    record_idx: int
    for record_idx, record in enumerate(history, start=1):
        print(
            f"step={record_idx} "
            f"action={record.get_action()} "
            f"reward={record.get_reward():.3f} "
            f"terminated={record.get_terminated()} "
            f"truncated={record.get_truncated()} "
            f"pf_converged={record.get_step_info().get_pf_converged()} "
            f"action_applied={record.get_step_info().get_action_applied()}"
        )

    return history


if __name__ == "__main__":
    run_demo(
        grid_path="files/IEEE 9 Bus.veragrid",
        steps=10,
        seed=7
    )

def build_ordered_free_indices(
    pv_indices: np.ndarray,
    pq_indices: np.ndarray,
) -> np.ndarray:
    """Build the state-bus order used by the rectangular formulation.

    PV buses are placed before PQ buses so that the equation ordering remains
    deterministic and directly inspectable.

    :param pv_indices: PV-bus indices.
    :param pq_indices: PQ-bus indices.
    :return: Ordered non-slack bus indices.
    """
    pv_count: int = pv_indices.size
    pq_count: int = pq_indices.size
    free_indices: np.ndarray = np.empty(pv_count + pq_count, dtype=np.int64)
    free_indices[:pv_count] = pv_indices
    free_indices[pv_count:] = pq_indices
    return free_indices


def build_rectangular_jacobian(
    y_bus: csc_matrix,
    anchor_v: np.ndarray,
    pv_indices: np.ndarray,
    pq_indices: np.ndarray,
    free_indices: np.ndarray,
) -> csc_matrix:
    """Build the CSC Jacobian of the quadratic rectangular power-flow chart.

    The equations are active-power balance at every non-slack bus, reactive-
    power balance at PQ buses, and squared-voltage constraints at PV buses.
    This formulation is exactly quadratic for constant-power injections.

    :param y_bus: CSC nodal admittance matrix.
    :param anchor_v: Complex anchor bus voltage in p.u.
    :param pv_indices: PV-bus indices.
    :param pq_indices: PQ-bus indices.
    :param free_indices: Ordered non-slack state-bus indices.
    :return: Square CSC rectangular Jacobian.
    """
    bus_count: int = anchor_v.size
    free_count: int = free_indices.size
    pq_count: int = pq_indices.size
    pv_count: int = pv_indices.size

    # The current at the anchor provides the diagonal terms generated by the
    # product V * conj(YV). Keeping this calculation explicit makes the local
    # quadratic linearization evident during inspection.
    anchor_current: np.ndarray = y_bus @ anchor_v
    voltage_real: np.ndarray = anchor_v.real
    voltage_imaginary: np.ndarray = anchor_v.imag
    current_real: np.ndarray = anchor_current.real
    current_imaginary: np.ndarray = anchor_current.imag

    conductance: csc_matrix = y_bus.real
    susceptance: csc_matrix = y_bus.imag
    conductance_free: csc_matrix = conductance[free_indices, :][:, free_indices]
    susceptance_free: csc_matrix = susceptance[free_indices, :][:, free_indices]

    voltage_real_free_diagonal: csc_matrix = diags(
        voltage_real[free_indices],
        offsets=0,
        shape=(free_count, free_count),
        format="csc",
    )
    voltage_imaginary_free_diagonal: csc_matrix = diags(
        voltage_imaginary[free_indices],
        offsets=0,
        shape=(free_count, free_count),
        format="csc",
    )
    current_real_free_diagonal: csc_matrix = diags(
        current_real[free_indices],
        offsets=0,
        shape=(free_count, free_count),
        format="csc",
    )
    current_imaginary_free_diagonal: csc_matrix = diags(
        current_imaginary[free_indices],
        offsets=0,
        shape=(free_count, free_count),
        format="csc",
    )

    # Active-power derivatives form the first equation block for every free
    # bus. These expressions are the exact derivatives in rectangular form.
    jacobian_p_real: csc_matrix = (
        current_real_free_diagonal
        + voltage_real_free_diagonal @ conductance_free
        + voltage_imaginary_free_diagonal @ susceptance_free
    )
    jacobian_p_imaginary: csc_matrix = (
        current_imaginary_free_diagonal
        - voltage_real_free_diagonal @ susceptance_free
        + voltage_imaginary_free_diagonal @ conductance_free
    )

    # A sparse selector maps each PQ equation to the same bus position in the
    # ordered free-state vector without introducing dense lookup structures.
    free_position: np.ndarray = np.full(bus_count, -1, dtype=np.int64)
    free_position[free_indices] = np.arange(free_count, dtype=np.int64)
    pq_rows: np.ndarray = np.arange(pq_count, dtype=np.int64)
    pq_columns: np.ndarray = free_position[pq_indices]
    pq_selector: csc_matrix = csc_matrix(
        (
            np.ones(pq_count, dtype=float),
            (pq_rows, pq_columns),
        ),
        shape=(pq_count, free_count),
    )

    conductance_pq: csc_matrix = conductance[pq_indices, :][:, free_indices]
    susceptance_pq: csc_matrix = susceptance[pq_indices, :][:, free_indices]
    voltage_real_pq_diagonal: csc_matrix = diags(
        voltage_real[pq_indices],
        offsets=0,
        shape=(pq_count, pq_count),
        format="csc",
    )
    voltage_imaginary_pq_diagonal: csc_matrix = diags(
        voltage_imaginary[pq_indices],
        offsets=0,
        shape=(pq_count, pq_count),
        format="csc",
    )
    current_real_pq_diagonal: csc_matrix = diags(
        current_real[pq_indices],
        offsets=0,
        shape=(pq_count, pq_count),
        format="csc",
    )
    current_imaginary_pq_diagonal: csc_matrix = diags(
        current_imaginary[pq_indices],
        offsets=0,
        shape=(pq_count, pq_count),
        format="csc",
    )

    jacobian_q_real: csc_matrix = (
        -current_imaginary_pq_diagonal @ pq_selector
        + voltage_imaginary_pq_diagonal @ conductance_pq
        - voltage_real_pq_diagonal @ susceptance_pq
    )
    jacobian_q_imaginary: csc_matrix = (
        current_real_pq_diagonal @ pq_selector
        - voltage_imaginary_pq_diagonal @ susceptance_pq
        - voltage_real_pq_diagonal @ conductance_pq
    )

    # PV equations preserve squared voltage magnitude. Their derivatives are
    # sparse selectors scaled by twice the anchor rectangular voltage parts.
    pv_rows: np.ndarray = np.arange(pv_count, dtype=np.int64)
    pv_columns: np.ndarray = free_position[pv_indices]
    pv_selector: csc_matrix = csc_matrix(
        (
            np.ones(pv_count, dtype=float),
            (pv_rows, pv_columns),
        ),
        shape=(pv_count, free_count),
    )
    voltage_real_pv_diagonal: csc_matrix = diags(
        2.0 * voltage_real[pv_indices],
        offsets=0,
        shape=(pv_count, pv_count),
        format="csc",
    )
    voltage_imaginary_pv_diagonal: csc_matrix = diags(
        2.0 * voltage_imaginary[pv_indices],
        offsets=0,
        shape=(pv_count, pv_count),
        format="csc",
    )
    jacobian_vm_real: csc_matrix = voltage_real_pv_diagonal @ pv_selector
    jacobian_vm_imaginary: csc_matrix = voltage_imaginary_pv_diagonal @ pv_selector

    # CSC is requested directly at construction because this matrix is stored,
    # factorized, and reused without subsequent sparse-format conversion.
    rectangular_jacobian: csc_matrix = bmat(
        (
            (jacobian_p_real, jacobian_p_imaginary),
            (jacobian_q_real, jacobian_q_imaginary),
            (jacobian_vm_real, jacobian_vm_imaginary),
        ),
        format="csc",
    )
    return rectangular_jacobian


def compose_first_order_right_hand_side(
    target_s: np.ndarray,
    patch: PowerFlowAtlasPatch,
) -> np.ndarray:
    """Compose the linear input-direction vector for one patch query.

    :param target_s: Target nodal complex injections in p.u.
    :param patch: Selected local atlas patch.
    :return: Dense real right-hand side in chart equation order.
    """
    anchor_s: np.ndarray = patch.get_anchor_s()
    pv_indices: np.ndarray = patch.get_pv_indices()
    pq_indices: np.ndarray = patch.get_pq_indices()
    free_indices: np.ndarray = patch.get_free_indices()
    free_count: int = free_indices.size
    pq_count: int = pq_indices.size
    pv_count: int = pv_indices.size
    right_hand_side: np.ndarray = np.zeros(2 * free_count, dtype=float)
    delta_s: np.ndarray = target_s - anchor_s

    # Only P is specified at PV buses. Q at a PV bus is an output and must not
    # be injected into the directional chart as an independent input.
    right_hand_side[:free_count] = delta_s.real[free_indices]
    right_hand_side[free_count:free_count + pq_count] = delta_s.imag[pq_indices]

    # This implementation keeps PV voltage setpoints fixed within each patch.
    # A future extension can add a target squared-voltage vector here without
    # changing the quadratic recurrence or the stored Jacobian.
    right_hand_side[free_count + pq_count:free_count + pq_count + pv_count] = 0.0
    return right_hand_side


def compose_higher_order_right_hand_side(
    order_index: int,
    voltage_coefficients: np.ndarray,
    current_coefficients: np.ndarray,
    patch: PowerFlowAtlasPatch,
) -> np.ndarray:
    """Compose the nonlinear convolution forcing for one higher series order.

    :param order_index: Series order currently being solved.
    :param voltage_coefficients: Preallocated per-order bus-voltage coefficients.
    :param current_coefficients: Preallocated per-order bus-current coefficients.
    :param patch: Selected local atlas patch.
    :return: Dense real right-hand side for the reused Jacobian factorization.
    """
    pv_indices: np.ndarray = patch.get_pv_indices()
    pq_indices: np.ndarray = patch.get_pq_indices()
    free_indices: np.ndarray = patch.get_free_indices()
    bus_count: int = voltage_coefficients.shape[1]
    free_count: int = free_indices.size
    pq_count: int = pq_indices.size
    pv_count: int = pv_indices.size

    lower_power_coefficient: np.ndarray = np.zeros(bus_count, dtype=np.complex128)
    lower_voltage_square_coefficient: np.ndarray = np.zeros(pv_count, dtype=np.complex128)

    # The network equations are quadratic, so every higher coefficient is a
    # convolution of already-known lower coefficients. No nonlinear iteration
    # is needed while the fixed control regime remains valid.
    convolution_index: int
    for convolution_index in range(1, order_index):
        lower_power_coefficient += (
            voltage_coefficients[convolution_index, :]
            * np.conj(current_coefficients[order_index - convolution_index, :])
        )
        lower_voltage_square_coefficient += (
            voltage_coefficients[convolution_index, pv_indices]
            * np.conj(voltage_coefficients[order_index - convolution_index, pv_indices])
        )

    right_hand_side: np.ndarray = np.zeros(2 * free_count, dtype=float)
    right_hand_side[:free_count] = -lower_power_coefficient.real[free_indices]
    right_hand_side[free_count:free_count + pq_count] = -lower_power_coefficient.imag[pq_indices]
    right_hand_side[free_count + pq_count:free_count + pq_count + pv_count] = (
        -lower_voltage_square_coefficient.real
    )
    return right_hand_side


def evaluate_voltage_polynomial(voltage_coefficients: np.ndarray) -> np.ndarray:
    """Evaluate a voltage series at the target path parameter ``t = 1``.

    :param voltage_coefficients: Per-order, per-bus complex coefficients.
    :return: Complex bus-voltage estimate.
    """
    voltage: np.ndarray = np.sum(voltage_coefficients, axis=0)
    return voltage


def evaluate_single_pade_series(
    coefficients: np.ndarray,
    minimum_denominator: float,
) -> tuple[complex, bool]:
    """Evaluate one scalar diagonal-like Padé approximant at ``t = 1``.

    :param coefficients: Scalar series coefficients from order zero upward.
    :param minimum_denominator: Minimum safe denominator magnitude.
    :return: Evaluated value and a safety flag.
    """
    coefficient_count: int = coefficients.size
    maximum_order: int = coefficient_count - 1
    denominator_order: int = maximum_order // 2
    numerator_order: int = maximum_order - denominator_order
    value: complex
    safe: bool

    if denominator_order == 0:
        value = complex(np.sum(coefficients))
        safe = True
    else:
        pade_matrix: np.ndarray = np.zeros(
            (denominator_order, denominator_order),
            dtype=np.complex128,
        )
        pade_right_hand_side: np.ndarray = np.zeros(
            denominator_order,
            dtype=np.complex128,
        )

        row_index: int
        column_index: int
        for row_index in range(denominator_order):
            coefficient_index: int = numerator_order + 1 + row_index
            pade_right_hand_side[row_index] = -coefficients[coefficient_index]
            for column_index in range(denominator_order):
                denominator_coefficient_index: int = column_index + 1
                source_index: int = coefficient_index - denominator_coefficient_index
                pade_matrix[row_index, column_index] = coefficients[source_index]

        denominator_coefficients: np.ndarray = np.zeros(
            denominator_order + 1,
            dtype=np.complex128,
        )
        denominator_coefficients[0] = 1.0 + 0.0j
        solved: bool = True
        try:
            denominator_coefficients[1:] = np.linalg.solve(
                pade_matrix,
                pade_right_hand_side,
            )
        except np.linalg.LinAlgError:
            solved = False

        if solved:
            numerator_coefficients: np.ndarray = np.zeros(
                numerator_order + 1,
                dtype=np.complex128,
            )
            numerator_index: int
            for numerator_index in range(numerator_order + 1):
                denominator_index: int
                maximum_denominator_index: int = min(
                    numerator_index,
                    denominator_order,
                )
                for denominator_index in range(maximum_denominator_index + 1):
                    numerator_coefficients[numerator_index] += (
                        denominator_coefficients[denominator_index]
                        * coefficients[numerator_index - denominator_index]
                    )

            numerator_value: complex = complex(np.sum(numerator_coefficients))
            denominator_value: complex = complex(np.sum(denominator_coefficients))
            if abs(denominator_value) >= minimum_denominator:
                value = numerator_value / denominator_value
                safe = True
            else:
                value = complex(np.sum(coefficients))
                safe = False
        else:
            value = complex(np.sum(coefficients))
            safe = False

    return value, safe


def evaluate_voltage_pade(
    voltage_coefficients: np.ndarray,
    minimum_denominator: float,
) -> tuple[np.ndarray, bool]:
    """Evaluate independent per-bus Padé approximants at ``t = 1``.

    :param voltage_coefficients: Per-order, per-bus complex coefficients.
    :param minimum_denominator: Minimum safe denominator magnitude.
    :return: Voltage estimate and a global safety flag.
    """
    bus_count: int = voltage_coefficients.shape[1]
    voltage: np.ndarray = np.zeros(bus_count, dtype=np.complex128)
    all_safe: bool = True
    bus_index: int
    for bus_index in range(bus_count):
        bus_value: complex
        bus_safe: bool
        bus_value, bus_safe = evaluate_single_pade_series(
            coefficients=voltage_coefficients[:, bus_index],
            minimum_denominator=minimum_denominator,
        )
        voltage[bus_index] = bus_value
        if bus_safe:
            all_safe = all_safe and True
        else:
            all_safe = False
    return voltage, all_safe


def calculate_directional_voltage_series(
    y_bus: csc_matrix,
    target_s: np.ndarray,
    patch: PowerFlowAtlasPatch,
    evaluation_method: SeriesEvaluationMethod,
    minimum_pade_denominator: float,
) -> DirectionalSeriesResult:
    """Generate and evaluate a query-direction voltage series.

    :param y_bus: Shared CSC nodal admittance matrix.
    :param target_s: Target nodal complex injections in p.u.
    :param patch: Selected fixed-regime local chart.
    :param evaluation_method: Polynomial or Padé evaluation.
    :param minimum_pade_denominator: Minimum safe Padé denominator magnitude.
    :return: Directional-series result including all bus coefficients.
    """
    anchor_v: np.ndarray = patch.get_anchor_v()
    free_indices: np.ndarray = patch.get_free_indices()
    bus_count: int = anchor_v.size
    series_order: int = patch.get_series_order()
    voltage_coefficients: np.ndarray = np.zeros(
        (series_order + 1, bus_count),
        dtype=np.complex128,
    )
    current_coefficients: np.ndarray = np.zeros(
        (series_order + 1, bus_count),
        dtype=np.complex128,
    )
    voltage_coefficients[0, :] = anchor_v
    current_coefficients[0, :] = y_bus @ anchor_v

    successful: bool = True
    message: str = "Directional series generated"
    order_index: int
    for order_index in range(1, series_order + 1):
        right_hand_side: np.ndarray
        if order_index == 1:
            right_hand_side = compose_first_order_right_hand_side(
                target_s=target_s,
                patch=patch,
            )
        else:
            right_hand_side = compose_higher_order_right_hand_side(
                order_index=order_index,
                voltage_coefficients=voltage_coefficients,
                current_coefficients=current_coefficients,
                patch=patch,
            )

        state_coefficient: np.ndarray = patch.solve_jacobian(right_hand_side)
        free_count: int = free_indices.size
        if np.all(np.isfinite(state_coefficient)):
            voltage_coefficients[order_index, free_indices] = (
                state_coefficient[:free_count]
                + 1.0j * state_coefficient[free_count:]
            )
            current_coefficients[order_index, :] = (
                y_bus @ voltage_coefficients[order_index, :]
            )
        else:
            successful = False
            message = "Non-finite directional coefficient"

    if successful:
        anchor_scale: np.ndarray = np.maximum(
            np.abs(anchor_v[free_indices]),
            0.1,
        )
        first_order_relative_motion: np.ndarray = (
            np.abs(voltage_coefficients[1, free_indices]) / anchor_scale
        )
        if first_order_relative_motion.size > 0:
            normalized_distance: float = float(np.max(first_order_relative_motion))
        else:
            normalized_distance = 0.0

        if evaluation_method == SeriesEvaluationMethod.Pade:
            voltage: np.ndarray
            pade_safe: bool
            voltage, pade_safe = evaluate_voltage_pade(
                voltage_coefficients=voltage_coefficients,
                minimum_denominator=minimum_pade_denominator,
            )
        else:
            voltage = evaluate_voltage_polynomial(voltage_coefficients)
            pade_safe = True
    else:
        voltage = anchor_v.copy()
        normalized_distance = float("inf")
        pade_safe = False

    result: DirectionalSeriesResult = DirectionalSeriesResult(
        successful=successful,
        message=message,
        voltage_coefficients=voltage_coefficients,
        voltage=voltage,
        normalized_distance=normalized_distance,
        pade_safe=pade_safe,
    )
    return result


def calculate_fixed_regime_residual(
    y_bus: csc_matrix,
    voltage: np.ndarray,
    target_s: np.ndarray,
    patch: PowerFlowAtlasPatch,
    reactive_limit_tolerance: float,
) -> FixedRegimeResidual:
    """Calculate the exact classical AC mismatch and PV-limit validity.

    :param y_bus: Shared CSC nodal admittance matrix.
    :param voltage: Candidate complex bus voltage in p.u.
    :param target_s: Target nodal complex injections in p.u.
    :param patch: Fixed-regime local chart.
    :param reactive_limit_tolerance: PV reactive-limit tolerance in p.u.
    :return: Exact mismatch and regime-verification result.
    """
    free_indices: np.ndarray = patch.get_free_indices()
    pq_indices: np.ndarray = patch.get_pq_indices()
    pv_indices: np.ndarray = patch.get_pv_indices()
    vm2_setpoint: np.ndarray = patch.get_vm2_setpoint()
    q_min: np.ndarray = patch.get_q_min()
    q_max: np.ndarray = patch.get_q_max()
    free_count: int = free_indices.size
    pq_count: int = pq_indices.size
    pv_count: int = pv_indices.size

    calculated_power: np.ndarray = voltage * np.conj(y_bus @ voltage)
    mismatch: np.ndarray = np.zeros(2 * free_count, dtype=float)
    mismatch[:free_count] = (
        calculated_power.real[free_indices] - target_s.real[free_indices]
    )
    mismatch[free_count:free_count + pq_count] = (
        calculated_power.imag[pq_indices] - target_s.imag[pq_indices]
    )
    mismatch[free_count + pq_count:free_count + pq_count + pv_count] = (
        np.square(np.abs(voltage[pv_indices])) - vm2_setpoint
    )

    if mismatch.size > 0:
        mismatch_norm: float = float(np.max(np.abs(mismatch)))
    else:
        mismatch_norm = 0.0

    if pv_count > 0:
        pv_reactive_power: np.ndarray = calculated_power.imag[pv_indices]
        lower_valid: np.ndarray = (
            pv_reactive_power >= q_min[pv_indices] - reactive_limit_tolerance
        )
        upper_valid: np.ndarray = (
            pv_reactive_power <= q_max[pv_indices] + reactive_limit_tolerance
        )
        reactive_limits_valid: bool = bool(np.all(lower_valid & upper_valid))
    else:
        reactive_limits_valid = True

    residual: FixedRegimeResidual = FixedRegimeResidual(
        mismatch=mismatch,
        norm=mismatch_norm,
        calculated_power=calculated_power,
        reactive_limits_valid=reactive_limits_valid,
    )
    return residual


def build_topology_signature(
    system_base_power: float,
    y_bus: csc_matrix,
    y_from: csc_matrix | None = None,
    y_to: csc_matrix | None = None,
    branch_from_indices: np.ndarray | None = None,
    branch_to_indices: np.ndarray | None = None,
) -> str:
    """Build a stable signature for voltage and branch-flow topology.

    The nodal matrix identifies the voltage equations. When complete terminal
    branch data is supplied, the signature also identifies the decomposition
    used to calculate individual branch currents and flows. Control regimes are
    intentionally excluded because one atlas may contain several active sets.

    :param system_base_power: System base power in MVA.
    :param y_bus: CSC nodal admittance matrix.
    :param y_from: Optional CSC from-terminal branch admittance matrix.
    :param y_to: Optional CSC to-terminal branch admittance matrix.
    :param branch_from_indices: Optional from-terminal bus indices.
    :param branch_to_indices: Optional to-terminal bus indices.
    :return: SHA-256 hexadecimal topology signature.
    """
    hash_builder: hashlib._Hash = hashlib.sha256()
    hash_builder.update(np.asarray(system_base_power, dtype=np.float64).tobytes())
    hash_builder.update(np.asarray(y_bus.shape, dtype=np.int64).tobytes())
    hash_builder.update(np.asarray(y_bus.indptr, dtype=np.int64).tobytes())
    hash_builder.update(np.asarray(y_bus.indices, dtype=np.int64).tobytes())
    hash_builder.update(np.asarray(y_bus.data, dtype=np.complex128).tobytes())

    branch_data_complete: bool = bool(
        y_from is not None
        and y_to is not None
        and branch_from_indices is not None
        and branch_to_indices is not None
    )
    branch_data_absent: bool = bool(
        y_from is None
        and y_to is None
        and branch_from_indices is None
        and branch_to_indices is None
    )
    if branch_data_complete:
        hash_builder.update(np.asarray((1,), dtype=np.int8).tobytes())
        hash_builder.update(np.asarray(y_from.shape, dtype=np.int64).tobytes())
        hash_builder.update(np.asarray(y_from.indptr, dtype=np.int64).tobytes())
        hash_builder.update(np.asarray(y_from.indices, dtype=np.int64).tobytes())
        hash_builder.update(np.asarray(y_from.data, dtype=np.complex128).tobytes())
        hash_builder.update(np.asarray(y_to.shape, dtype=np.int64).tobytes())
        hash_builder.update(np.asarray(y_to.indptr, dtype=np.int64).tobytes())
        hash_builder.update(np.asarray(y_to.indices, dtype=np.int64).tobytes())
        hash_builder.update(np.asarray(y_to.data, dtype=np.complex128).tobytes())
        hash_builder.update(
            np.asarray(branch_from_indices, dtype=np.int64).tobytes()
        )
        hash_builder.update(
            np.asarray(branch_to_indices, dtype=np.int64).tobytes()
        )
    else:
        if branch_data_absent:
            hash_builder.update(np.asarray((0,), dtype=np.int8).tobytes())
        else:
            hash_builder.update(np.asarray((-1,), dtype=np.int8).tobytes())
    signature: str = hash_builder.hexdigest()
    return signature


def get_objects_dictionary() -> Dict[str, ALL_DEV_TYPES]:
    """
    creates a dictionary with the types and the circuit objects
    :return: Dictionary instance
    """

    # this list must be sorted in dependency order so that the
    # loading algorithm is able to find the object substitutions

    object_types = {

        'bus': Bus(),

        'load': Load(),

        'static_generator': StaticGenerator(),

        'battery': Battery(),

        'generator': Generator(),

        'shunt': Shunt(),

        'linear_shunt': ControllableShunt(),

        'external_grid': ExternalGrid(),

        'current_injection': CurrentInjection(),

        'transformer2w': Transformer2W(),

        'windings': Winding(),
        'transformer3w': Transformer3W(),

        'line': Line(),

        'dc_line': DcLine(),

        'hvdc': HvdcLine(),

        'vsc': VSC(),

        'upfc': UPFC(),

        'series_reactance': SeriesReactance(),

        'switch': Switch(),

    }
    return object_types


class RmsModelTemplate(EditableDevice):
    """
    This class serves to give flexible access to either a template or a custom model
    """

    __slots__ = (
        '_block',
        '_api_object')


    def __init__(self, name: str = ""):
        super().__init__(name=name,
                         idtag=None,
                         code="",
                         device_type=DeviceType.RmsModelTemplateDevice)
        self._api_object: ALL_DEV_TYPES | None = None
        self._block: Block = Block()



    @property
    def block(self):
        return self._block

    @block.setter
    def block(self, obj: Block):
        self._block = obj

    @property
    def api_object(self):
        return self._api_object

    @api_object.setter
    def api_object(self, obj: ALL_DEV_TYPES):
        self._api_object = obj


    def to_dict(self) -> Dict[str, int | Dict[str, List[Dict[str, Any]]]]:
        """
        Generate a dictionary to save
        :return: Data to save
        """
        return {
            "device_type": self.api_object.device_type.value if self.api_object is not None else None,
            "block": self.block.to_dict()
        }

    def parse(self, data: Dict[str, str | Dict[str, List[Dict[str, Any]]]]):
        """
        Parse the data
        :param data: data generated by to_dict

        """
        objects_dict = get_objects_dictionary()
        self.api_object = objects_dict.get(data["device_type"], None)
        self.block = Block().parse(data = data["block"])